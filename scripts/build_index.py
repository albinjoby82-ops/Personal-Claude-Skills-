#!/usr/bin/env python3
"""Validate every skill and rebuild the index in README.md.

Usage:  python3 scripts/build_index.py          # validate + rewrite README index
        python3 scripts/build_index.py --check  # validate only (exit 1 on problems)
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
README = ROOT / "README.md"
START, END = "<!-- INDEX:START -->", "<!-- INDEX:END -->"
CATEGORIES = ["study", "ee", "git", "writing", "tools", "other"]
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta


def main():
    errors, rows = [], []
    for d in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        f = d / "SKILL.md"
        if not f.exists():
            errors.append(f"{d.name}: missing SKILL.md")
            continue
        meta = parse(f)
        if meta is None:
            errors.append(f"{d.name}: no frontmatter")
            continue
        name, desc = meta.get("name", ""), meta.get("description", "")
        cat = meta.get("category", "other")
        if name != d.name:
            errors.append(f"{d.name}: frontmatter name '{name}' must equal folder name")
        if not NAME_RE.match(d.name) or len(d.name) > 40:
            errors.append(f"{d.name}: name must be lowercase-kebab-case, max 40 chars")
        if not desc or len(desc) > 200 or "<" in desc or ">" in desc:
            errors.append(f"{d.name}: description needed, max 200 chars, no angle brackets")
        if cat not in CATEGORIES:
            errors.append(f"{d.name}: category '{cat}' not in {CATEGORIES}")
        rows.append((cat, d.name, desc, meta.get("tags", "")))

    for e in errors:
        print("ERROR:", e)
    if errors:
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"OK: {len(rows)} skills")
        return

    out = [f"_{len(rows)} skills. Auto-generated by `scripts/build_index.py`, do not edit by hand._", ""]
    for cat in CATEGORIES:
        items = [r for r in rows if r[0] == cat]
        if not items:
            continue
        out += [f"### {cat}", "", "| Skill | What it does | Tags |", "|---|---|---|"]
        for _, name, desc, tags in items:
            out.append(f"| [`{name}`](skills/{name}/SKILL.md) | {desc} | {tags.strip('[]')} |")
        out.append("")
    block = f"{START}\n" + "\n".join(out) + f"\n{END}"
    text = README.read_text(encoding="utf-8")
    new = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    README.write_text(new, encoding="utf-8")
    print(f"Index rebuilt: {len(rows)} skills")


main()
